let currentLang = localStorage.getItem("bassma_lang") || "ar";

function setLanguage(lang) {
  if (lang !== "ar" && lang !== "fr") lang = "ar";
  currentLang = lang;
  localStorage.setItem("bassma_lang", lang);

  const docEl = document.documentElement;
  docEl.lang = lang;
  docEl.dir = lang === "ar" ? "rtl" : "ltr";

  // Update all elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key] !== undefined) {
      el.textContent = translations[lang][key];
    }
  });

  // Update all elements with data-i18n-placeholder
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[lang] && translations[lang][key] !== undefined) {
      el.placeholder = translations[lang][key];
    }
  });

  // Update language toggle buttons UI
  const btnAr = document.getElementById("langBtnAr");
  const btnFr = document.getElementById("langBtnFr");
  if (btnAr && btnFr) {
    if (lang === "ar") {
      btnAr.classList.add("bg-sky-500", "text-white", "font-bold");
      btnAr.classList.remove("text-sky-200", "hover:bg-sky-900/50");
      btnFr.classList.remove("bg-sky-500", "text-white", "font-bold");
      btnFr.classList.add("text-sky-200", "hover:bg-sky-900/50");
    } else {
      btnFr.classList.add("bg-sky-500", "text-white", "font-bold");
      btnFr.classList.remove("text-sky-200", "hover:bg-sky-900/50");
      btnAr.classList.remove("bg-sky-500", "text-white", "font-bold");
      btnAr.classList.add("text-sky-200", "hover:bg-sky-900/50");
    }
  }

  // Trigger custom event so maps, charts, dynamic lists re-render
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

